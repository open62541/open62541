from __future__ import print_function
import argparse
import sys
from io import open

parser = argparse.ArgumentParser()
parser.add_argument('statuscodes', help='path/to/Opc.Ua.NodeIds.csv')
parser.add_argument('outfile', help='outfile w/o extension')
parser.add_argument('namespace', help='NS0')
args = parser.parse_args()

rows = []
with open(args.statuscodes, mode="rt") as f:
    lines = f.readlines()
    for l in lines:
        rows.append(tuple(l.strip().split(',')))

fh = open(args.outfile + ".h", "wt", encoding='utf8')
def printh(string):
    print(string, end=u'\n', file=fh)

#########################
# Print the header file #
#########################

printh(u'''/**********************************
 * Autogenerated -- do not modify *
 **********************************/

#ifndef UA_NODEIDS_{0}_H_
#define UA_NODEIDS_{0}_H_

/**
 * Namespace Zero NodeIds
 * ----------------------
 * Numeric identifiers of standard-defined nodes in namespace zero. The
 * following definitions are autogenerated from a CSV file */
'''.format(args.namespace))

# Different CSV rows can result in the same macro name (e.g. the names differ
# only in the case). Emit every macro once. Conflicting definitions are reported.
# The last definition is kept, which is what the compiler would use when
# processing a redefinition.
lastIndex = {}
conflicts = {}
for i, row in enumerate(rows):
    name = row[0].upper()
    if name in lastIndex and rows[lastIndex[name]][1] != row[1]:
        conflicts.setdefault(name, [rows[lastIndex[name]][1]]).append(row[1])
    lastIndex[name] = i

for name in sorted(conflicts):
    print(u"Warning: Macro UA_{0}ID_{1} is defined for several NodeIds ({2}). "
          u"Using {3}.".format(args.namespace, name, u", ".join(conflicts[name]),
                               conflicts[name][-1]), file=sys.stderr)

for i, row in enumerate(rows):
    if lastIndex[row[0].upper()] != i:
        continue
    printh(u"#define UA_{namespace}ID_{name} {id} /* {description} */".format(namespace=args.namespace, name=row[0].upper(), id=row[1], description=row[2]))

printh(u'''#endif /* UA_NODEIDS_{0}_H_ */ '''.format(args.namespace))

fh.close()
